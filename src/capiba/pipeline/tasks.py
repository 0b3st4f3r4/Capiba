def task_run_pipeline(spec_path: str, **context: Any) -> dict[str, Any]:
    """Task: run a declarative (YAML) ingestion pipeline.

    Loads the pipeline spec, resolves the run date from the Airflow context
    and executes the pipeline through ``capiba.pipeline.runner`` (the run
    report is published to the gold layer when the spec declares the
    ``gold_report`` destination). Post steps declared in the spec
    (``dbt_run``, ``detect``) run after the pipeline, reusing the existing
    task functions.

    Args:
        spec_path: Path of the YAML pipeline spec.
        context: Airflow context.

    Returns:
        Execution summary (pipeline name, success, step count, post steps).
    """
    from capiba.pipeline.runner import run_pipeline
    from capiba.pipeline.spec import load_spec

    run_date = _lake_run_date(context) or date.today()
    spec = load_spec(spec_path)
    logger.info("Running declarative pipeline '%s' for %s", spec.name, run_date)

    report = run_pipeline(spec, run_date)

    post_results: dict[str, Any] = {}
    for step in spec.post_steps:
        if step == "dbt_run":
            post_results["dbt_run"] = task_dbt_run(**context)
        elif step == "detect":
            post_results["detect"] = task_detect(**context)

    return {
        "pipeline": report.pipeline,
        "success": report.success,
        "steps": len(report.steps),
        "post_steps": post_results,
    }

"""Atomic transformation tasks.

Responsibility: pure functions (``normalize_contracts``, ``validate_contracts``,
``persist_contracts``) implementing each step of the ingestion pipeline,
with no Airflow dependency. The ``task_*`` wrappers adapt these functions to
the Airflow context (XCom, ``ds``) and are called by the DAG operators;
``scripts/ingestion.py`` reuses the pure functions directly.

``task_run_pipeline`` is the entrypoint of the declarative framework: the
DAGs generated by ``dags/pipeline_factory.py`` from ``dags/pipelines/*.yaml``
call it with the spec path, delegating execution to
``capiba.pipeline.runner``.
"""


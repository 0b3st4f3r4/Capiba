"""Atomic transformation tasks.

Responsibility: pure functions (``validate_contracts``, ``persist_contracts``)
implementing steps of the ingestion pipeline, with no Airflow dependency,
reused by ``capiba.pipeline.runner``. The ``task_*`` wrappers adapt the
declarative pipeline steps to the Airflow context (XCom, ``ds``) and are
called by the DAG operators generated by ``dags/pipeline_factory.py`` from
``dags/pipelines/*.yaml``; ``scripts/ingestion.py`` executes the same specs
through the runner, without Airflow.

``task_run_pipeline`` is the entrypoint of the declarative framework: the
DAGs call it with the spec path, delegating execution to
``capiba.pipeline.runner``.
"""

